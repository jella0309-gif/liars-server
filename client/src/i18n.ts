const dictionaries: Record<Lang, Record<Key, string>> = { vi, en };

function readStoredLang(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'vi' || stored === 'en') return stored;
  } catch {
    /* storage unavailable */
  }
  return 'vi';
}

export const useI18n = create<{ lang: Lang; setLang: (lang: Lang) => void }>(
  (set) => ({
    lang: readStoredLang(),
    setLang: (lang) => {
      try {
        localStorage.setItem(STORAGE_KEY, lang);
      } catch {
        /* storage unavailable */
      }
      document.documentElement.lang = lang;
      set({ lang });
    },
  })
);
document.documentElement.lang = useI18n.getState().lang;

export type Vars = Record<string, string | number>;

function format(template: string, vars?: Vars) {
  return vars
    ? template.replace(/\{(\w+)\}/g, (m, k) =>
        k in vars ? String(vars[k]) : m
      )
    : template;
}

/** Translate outside React (store, socket handlers) using the current language. */
export function t(key: Key, vars?: Vars): string {
  const lang = useI18n.getState().lang;
  return format(dictionaries[lang][key] ?? dictionaries.vi[key] ?? key, vars);
}

/** Translate inside components; re-renders on language change. */
export function useT() {
  const lang = useI18n((s) => s.lang);
  return (key: Key, vars?: Vars) =>
    format(dictionaries[lang][key] ?? dictionaries.vi[key] ?? key, vars);
}
